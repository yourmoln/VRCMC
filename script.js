const languageSelect = document.querySelector("[data-language-select]");
const navToggle = document.querySelector(".nav-toggle");
const primaryNav = document.querySelector(".primary-nav");
const siteHeader = document.querySelector(".site-header");
const copyButton = document.querySelector("[data-copy-target]");
const toast = document.querySelector("[data-toast]");
const supportedLocales = Object.keys(translations);

function resolveLocale(locale) {
  if (!locale) return "zh-CN";
  if (locale === "zh-TW" || locale === "zh-HK" || locale === "zh-Hant") return "zh-TW";
  if (locale.startsWith("zh")) return "zh-CN";
  if (locale.startsWith("ja")) return "ja";
  if (locale.startsWith("en")) return "en";
  return "zh-CN";
}

function applyLanguage(locale, persist = true) {
  const resolved = resolveLocale(locale);
  const strings = translations[resolved];

  document.documentElement.lang = resolved;
  document.title = strings["meta.title"];
  document.querySelector('meta[name="description"]')?.setAttribute("content", strings["meta.description"]);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = strings[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = strings[element.dataset.i18nAlt];
    if (value) element.alt = value;
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = strings[element.dataset.i18nAriaLabel];
    if (value) element.setAttribute("aria-label", value);
  });

  if (languageSelect) languageSelect.value = resolved;
  if (persist) {
    try {
      localStorage.setItem("vrcmc-promo-language", resolved);
    } catch {
      // Storage can be unavailable in privacy-focused browsing modes.
    }
  }
}

function initializeLanguage() {
  let stored = null;
  try {
    stored = localStorage.getItem("vrcmc-promo-language");
  } catch {
    // Fall through to the browser language.
  }

  const requested = new URLSearchParams(window.location.search).get("lang");
  const browserLocale = navigator.languages?.[0] || navigator.language;
  const initial = supportedLocales.includes(requested)
    ? requested
    : supportedLocales.includes(stored)
      ? stored
      : resolveLocale(browserLocale);

  applyLanguage(initial, false);
}

function closeNavigation() {
  if (!navToggle || !primaryNav) return;
  navToggle.setAttribute("aria-expanded", "false");
  primaryNav.classList.remove("is-open");
}

function showToast(message) {
  if (!toast) return;
  toast.textContent = message;
  toast.classList.add("is-visible");
  window.clearTimeout(showToast.timeout);
  showToast.timeout = window.setTimeout(() => toast.classList.remove("is-visible"), 1800);
}

function updateCopyButtonLabel() {
  if (!copyButton) return;
  const label = copyButton.querySelector("[data-i18n]");
  if (label) {
    label.dataset.i18n = "how.copy";
    label.textContent = translations[resolveLocale(document.documentElement.lang)]["how.copy"];
  }
}

initializeLanguage();

languageSelect?.addEventListener("change", (event) => {
  applyLanguage(event.target.value);
  updateCopyButtonLabel();
});

navToggle?.addEventListener("click", () => {
  const willOpen = navToggle.getAttribute("aria-expanded") !== "true";
  navToggle.setAttribute("aria-expanded", String(willOpen));
  primaryNav?.classList.toggle("is-open", willOpen);
});

primaryNav?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", closeNavigation);
});

document.addEventListener("click", (event) => {
  if (!primaryNav?.classList.contains("is-open")) return;
  if (!primaryNav.contains(event.target) && !navToggle?.contains(event.target)) closeNavigation();
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeNavigation();
});

copyButton?.addEventListener("click", async () => {
  const target = document.getElementById(copyButton.dataset.copyTarget);
  if (!target) return;

  const text = target.textContent.trim();
  try {
    await navigator.clipboard.writeText(text);
  } catch {
    const range = document.createRange();
    range.selectNodeContents(target);
    const selection = window.getSelection();
    selection.removeAllRanges();
    selection.addRange(range);
    document.execCommand("copy");
    selection.removeAllRanges();
  }

  const strings = translations[resolveLocale(document.documentElement.lang)];
  const label = copyButton.querySelector("[data-i18n]");
  if (label) {
    label.dataset.i18n = "how.copied";
    label.textContent = strings["how.copied"];
  }
  showToast(strings["how.copied"]);
  window.setTimeout(updateCopyButtonLabel, 1800);
});

function updateHeader() {
  siteHeader?.classList.toggle("is-scrolled", window.scrollY > 18);
}

window.addEventListener("scroll", updateHeader, { passive: true });
updateHeader();

